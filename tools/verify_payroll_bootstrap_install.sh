#!/usr/bin/env bash
set -euo pipefail

baseline=$1
candidate=$2
package=com.briskers.briskers_app
state=/data/user/0/$package
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

case "$(basename "$baseline")" in
  Briskers-v0.10.9-b2565.apk) expected=d23e5d325db3e0470a07ea6b1d43973ea592c5f77246960da4d74d1d6d496342 ;;
  Briskers-v0.10.9-b2566.apk) expected=62cb4723999c8767a9af128828837d297d0add476c899f7505ebbdde58c174d9 ;;
  Briskers-v0.10.9-b2567.apk) expected=e92e6d3884aac51d579550acbd0cd13713aa9d17381e5b327be6d7cb1eeee952 ;;
  Briskers-v0.10.9-b2568.apk) expected=b2e86c27dbd822127f74d2e75e56c0828bce85dc95efa88d9c19b2e0d1a51a88 ;;
  *) echo "Unknown signed upgrade baseline" >&2; exit 1 ;;
esac
printf '%s  %s\n' "$expected" "$baseline" | sha256sum -c
adb install "$baseline"
adb root
adb wait-for-device
test "$(adb shell id -u | tr -d '\r')" = 0
uid=$(adb shell stat -c %u "$state" | tr -d '\r')
[[ "$uid" =~ ^[0-9]+$ && "$uid" -gt 10000 ]]

# Emulator-only synthetic shop: discover the production database path after
# the trusted baseline launches, then install a fixture generated by b2568 APIs.
fixture=${BRISKERS_UPGRADE_FIXTURE:?Baseline fixture required}
evidence=generated/build/app/outputs/flutter-apk/upgrade-evidence
mkdir -p "$evidence"
adb shell svc wifi disable
adb shell svc data disable
adb logcat -c
launch() {
  adb shell am start -W -n "$package/.MainActivity"
  sleep 15
  adb shell pidof "$package"
}
launch
for attempt in $(seq 1 30); do
  dbpath=$(adb shell "find '$state' -name 'briskers_local.sqlite' -type f" | tr -d '\r' | head -1)
  if [ -n "$dbpath" ]; then break; fi
  sleep 2
done
test -n "$dbpath"
adb shell am force-stop "$package"
python3 tools/upgrade_retention.py prefs "$fixture.prefs.json" "$tmp/preferences.xml"
python3 tools/upgrade_retention.py snapshot "$fixture" "$evidence/baseline-records.json"
adb push "$fixture" "$dbpath"
adb shell "rm -f '$dbpath-wal' '$dbpath-shm'; mkdir -p '$state/shared_prefs'"
adb push "$tmp/preferences.xml" "$state/shared_prefs/FlutterSharedPreferences.xml"
adb shell "chown -R '$uid:$uid' '$state'; restorecon -R '$state'"
check_records() {
  phase=$1
  adb shell am force-stop "$package"
  adb pull "$dbpath" "$tmp/$phase.sqlite"
  if adb shell "test -f '$dbpath-wal'"; then
    adb pull "$dbpath-wal" "$tmp/$phase.sqlite-wal"
  fi
  adb pull "$state/shared_prefs/FlutterSharedPreferences.xml" "$tmp/$phase.xml"
  python3 tools/upgrade_retention.py verify "$evidence/baseline-records.json" "$tmp/$phase.sqlite" \
    --prefs "$tmp/$phase.xml" --expected-prefs "$tmp/preferences.xml" | tee "$evidence/$phase.json"
}
launch
check_records baseline-launched
adb install -r "$candidate" | tee "$evidence/install-result.txt"
test "$(adb shell stat -c %u "$state" | tr -d '\r')" = "$uid"
check_records after-install
launch
adb exec-out screencap -p > "$evidence/updated-first-launch.png"
check_records after-launch
launch
adb exec-out screencap -p > "$evidence/updated-restart.png"
check_records after-restart
adb logcat -d > "$evidence/emulator-logcat.txt"
if grep -E 'FATAL EXCEPTION|Fatal signal [0-9]+.*briskers' "$evidence/emulator-logcat.txt"; then
  echo "Emulator app crashed" >&2; exit 1
fi
printf '%s\n' "baseline=$(basename "$baseline")" "candidate=$(basename "$candidate")" \
  "app_id=$package" "uid=$uid" "database=$dbpath" \
  'physical_owner_phone_acceptance=NOT_PERFORMED' > "$evidence/identity.txt"
echo "Verified actual signed update, two app launches, SQLite records, payroll, pending/conflict states and Force Offline preferences."
