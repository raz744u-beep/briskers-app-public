#!/usr/bin/env bash
set -euo pipefail

baseline=$1
candidate=$2
package=com.briskers.briskers_app
state=/data/user/0/$package
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

case "$(basename "$baseline")" in
  Briskers-v0.10.9-b2565.apk) expected=d23e5d325db3e0470a07ea6b1d43973ea592c5f77246960da4d74d1d6d496342 ;;
  Briskers-v0.10.9-b2566.apk) expected=62cb4723999c8767a9af128828837d297d0add476c899f7505ebbdde58c174d9 ;;
  Briskers-v0.10.9-b2567.apk) expected=e92e6d3884aac51d579550acbd0cd13713aa9d17381e5b327be6d7cb1eeee952 ;;
  Briskers-v0.10.9-b2568.apk) expected=b2e86c27dbd822127f74d2e75e56c0828bce85dc95efa88d9c19b2e0d1a51a88 ;;
  *) echo "Unknown signed upgrade baseline" >&2; exit 1 ;;
esac
printf '%s  %s\n' "$expected" "$baseline" | sha256sum -c
adb install "$baseline"
adb root
adb wait-for-device
test "$(adb shell id -u | tr -d '\r')" = 0
uid=$(adb shell stat -c %u "$state" | tr -d '\r')
[[ "$uid" =~ ^[0-9]+$ && "$uid" -gt 10000 ]]

# Emulator-only synthetic shop: discover the production database path after
# the trusted baseline launches, then install a fixture generated by b2568 APIs.
fixture=${BRISKERS_UPGRADE_FIXTURE:?Baseline fixture required}
evidence=generated/build/app/outputs/flutter-apk/upgrade-evidence
mkdir -p "$evidence"
adb shell svc wifi disable
adb shell svc data disable
adb logcat -c
launch() {
  adb shell am start -W -n "$package/.MainActivity"
  sleep 15
  adb shell pidof "$package"
}
launch
for attempt in $(seq 1 30); do
  dbpath=$(adb shell "find '$state' -name 'briskers_local.sqlite' -type f" | tr -d '\r' | head -1)
  if [ -n "$dbpath" ]; then break; fi
  sleep 2
done
test -n "$dbpath"
adb shell am force-stop "$package"
python3 tools/upgrade_retention.py prefs "$fixture.prefs.json" "$tmp/preferences.xml"
python3 tools/upgrade_retention.py snapshot "$fixture" "$evidence/baseline-records.json"
adb push "$fixture" "$dbpath"
adb shell "rm -f '$dbpath-wal' '$dbpath-shm'; mkdir -p '$state/shared_prefs'"
adb push "$tmp/preferences.xml" "$state/shared_prefs/FlutterSharedPreferences.xml"
adb shell "chown -R '$uid:$uid' '$state'; restorecon -R '$state'"
# Preserve a real image payload alongside synthetic database and preference records.
photo="$state/app_flutter/receipts/upgrade-fixture.png"
adb exec-out screencap -p > "$tmp/photo.png"
adb shell "mkdir -p '$state/app_flutter/receipts'"
adb push "$tmp/photo.png" "$photo"
adb shell "chown '$uid:$uid' '$photo'; restorecon '$photo'"
check_records() {
  phase=$1
  adb shell am force-stop "$package"
  adb pull "$photo" "$tmp/$phase-photo.png"
  cmp "$tmp/photo.png" "$tmp/$phase-photo.png"
  adb pull "$dbpath" "$tmp/$phase.sqlite"
  if adb shell "test -f '$dbpath-wal'"; then
    adb pull "$dbpath-wal" "$tmp/$phase.sqlite-wal"
  fi
  adb pull "$state/shared_prefs/FlutterSharedPreferences.xml" "$tmp/$phase.xml"
  python3 tools/upgrade_retention.py verify "$evidence/baseline-records.json" "$tmp/$phase.sqlite" \
    --prefs "$tmp/$phase.xml" --expected-prefs "$tmp/preferences.xml" | tee "$evidence/$phase.json"
}
launch
check_records baseline-launched
# Keep the same synthetic app sandbox throughout both normal Android updates.
# The intermediate is the latest receipt build, not another TEST application.
intermediate=${BRISKERS_UPGRADE_INTERMEDIATE:-}
if [ -n "$intermediate" ]; then
  case "$(basename "$intermediate")" in
    Briskers-v0.10.9-b4646.apk) intermediate_hash=229311aa1d6b8b4935c3ec60d4684e2ec683e8204f732334248d3e07502ca590 ;;
    Briskers-v0.10.9-b4645.apk) intermediate_hash=55142e76737d18ceafcfca603b18dc98e8c5fa4b358480e2d12f87dd79fd4024 ;;
    Briskers-v0.10.9-b4640.apk) intermediate_hash=aab06ea48b27a55b23aa5378156ef7906bfcc63c4e3a9aea8c714c6a219fc70a ;;
    Briskers-v0.10.9-b4638.apk) intermediate_hash=8ca7c81de6fdc771e78bcf190637209f831242c00606e38c328833266bf0d830 ;;
    Briskers-v0.10.9-b4635.apk) intermediate_hash=b51a2e6e65a6feb567675a3a1cec8402c999f170d4beed556c43a678c2a2adeb ;;
    Briskers-v0.10.9-b4632.apk) intermediate_hash=1865ec9bd59553b5a52b396a5663b4eae20369dd0bbe04278181cd086fc6c009 ;;
    Briskers-v0.10.9-b4629.apk) intermediate_hash=17626f8317b3851bc780781f18ad0baf8360168c430d06f666983e4480848fb2 ;;
    Briskers-v0.10.9-b4627.apk) intermediate_hash=72b0d373ede19de9a99a6abaefcd6c4de7a5d381fbbad967ca97a32128f574b7 ;;
    Briskers-v0.10.9-b4620.apk) intermediate_hash=029c4407114f1f9894caabf5f95bb1ba50e46fd21ef4b09c52adda09ab91ac92 ;;
    Briskers-v0.10.9-b2571.apk) intermediate_hash=820845a388b63696525ccd7b2347a7690fec00690a227dd6ceb473f426572f2b ;;
    Briskers-v0.10.9-b2581.apk) intermediate_hash=50cadbc0d6a64fd8694e6dd78b0339634c746cbd83d6e84a8ec6c14b7b6a51b9 ;;
    Briskers-v0.10.9-b2582.apk) intermediate_hash=8737f3609320588081370fcfbf694f7cc7ca1b207c7c57df52bd9d5994858284 ;;
    Briskers-v0.10.9-b2587.apk) intermediate_hash=3dd35d27decc90174dc1432970de5459baaa78ae4def068a126d27838ac353af ;;
    Briskers-v0.10.9-b2586.apk) intermediate_hash=3e131b8fd491714b709d31838fbb3a3009f7626c540774a4b0056d869602d59b ;;
    *) echo 'Unknown signed intermediate APK' >&2; exit 1 ;;
  esac
  printf '%s  %s\n' "$intermediate_hash" "$intermediate" | sha256sum -c
  adb install -r "$intermediate" | tee "$evidence/intermediate-install-result.txt"
  test "$(adb shell stat -c %u "$state" | tr -d '\r')" = "$uid"
  launch
  check_records receipt-baseline-launched
fi
adb install -r "$candidate" | tee "$evidence/install-result.txt"
test "$(adb shell stat -c %u "$state" | tr -d '\r')" = "$uid"
check_records after-install
launch
adb exec-out screencap -p > "$evidence/updated-first-launch.png"
check_records after-launch
launch
adb exec-out screencap -p > "$evidence/updated-restart.png"
check_records after-restart
adb logcat -d > "$evidence/emulator-logcat.txt"
if grep -E 'FATAL EXCEPTION|Fatal signal [0-9]+.*briskers' "$evidence/emulator-logcat.txt"; then
  echo "Emulator app crashed" >&2; exit 1
fi
printf '%s\n' "baseline=$(basename "$baseline")" "candidate=$(basename "$candidate")" "intermediate=${intermediate##*/}" \
  "app_id=$package" "uid=$uid" "database=$dbpath" \
  'physical_owner_phone_acceptance=NOT_PERFORMED' > "$evidence/identity.txt"
echo "Verified actual signed update, two app launches, SQLite records, payroll, pending/conflict states and Force Offline preferences."
